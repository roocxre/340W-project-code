"""Load the 70 / 20 / 10 split of the joined n-back table for downstream models.

    import sys; sys.path.insert(0, "analysis")
    from nbacksplit import load, feature_columns, zscore_within_subject, windows

    tr = zscore_within_subject(load("train"))
    X, y = tr[feature_columns(tr)].to_numpy(), tr.n.to_numpy()

Within-subject z-scoring uses no labels and no other subject, and every subject sits in
exactly one split, so applying it to each split separately does not leak.
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
WINDOWS = ROOT.parent / "synthesis" / "cache" / "windows"
SPLITS = ("train", "test", "val")


def load(split, clean=False):
    """One split as a DataFrame; ``clean=True`` drops artifact windows (> 150 µV peak-to-peak)."""
    if split not in SPLITS:
        raise ValueError(f"split must be one of {SPLITS}")
    df = pd.read_csv(DATA / f"{split}.csv")
    return df[~df.artifact].reset_index(drop=True) if clean else df


def feature_columns(df):
    return [c for c in df.columns if c.startswith(("abs_", "rel_"))]


def zscore_within_subject(df, cols=None):
    """Copy of ``df`` with feature columns z-scored over each subject's rows."""
    cols = feature_columns(df) if cols is None else cols
    out = df.copy()
    g = out.groupby("subject")[cols]
    out[cols] = (out[cols] - g.transform("mean")) / (g.transform("std", ddof=0) + 1e-12)
    return out


def windows(df):
    """EEG windows for the rows of ``df``: float32 µV, shape (len(df), 26, 800) at 200 Hz.

    Reads synthesis/cache/windows/<subject>.npz (regenerated by synthesis stage 2).
    """
    out = np.empty((len(df), 26, 800), dtype=np.float32)
    for subject, idx in df.groupby("subject").indices.items():
        out[idx] = np.load(WINDOWS / f"{subject}.npz")["x"][df.npz_index.to_numpy()[idx]]
    return out
