"""Stage 7: paper-vs-ours tables -> results/paper_vs_ours.md."""
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from backrepro import data, paper  # noqa: E402


def load(name):
    with open(data.RESULTS / name) as f:
        return json.load(f)


def main():
    psd, cor, beam = load("psd.json"), load("correlation.json"), load("beam.json")
    anova = pd.read_csv(data.RESULTS / "anova.csv")
    clf = pd.read_csv(data.RESULTS / "classification.csv")
    out = ["# Paper vs ours", "",
           "Shafi et al. 2026, *Scientific Data*, doi:10.1038/s41597-026-07607-3. Generated by `scripts/07_report.py`.", ""]

    out += ["## Fig. 5: PSD across workload, Fp1-A1", "",
            f"Matched by subject {psd['fig5']['match_mne']} with the released `compute_psd_mne` (n_fft 2048); "
            f"`compute_psd_welch` matches {psd['fig5']['match_welch'] or 'no subject'}.", "",
            "| Condition | Paper peak (Hz) | sub02 peak | Paper power ratio | sub02 ratio | 30 clean subjects, median ratio [IQR] |",
            "|---|---|---|---|---|---|"]
    for c in data.CONDITIONS:
        r = psd["fig5"]["sub02"][c]
        g = psd["fig5_clean_subjects"]["ratios"].get(c)
        gtxt = f"{g['median_ratio']:.2f} [{g['q1']:.2f}-{g['q3']:.2f}]" if g else "1 (reference)"
        out.append(f"| {c} | {paper.FIG5[c][0]} | {r['peak']:.2f} | {paper.FIG5[c][1]} | {r['ratio']:.2f} | {gtxt} |")
    fc = psd["fig5_clean_subjects"]
    out += ["", f"- Rest peaks in the alpha band in {fc['nw_alpha_peak']}/30 clean subjects; "
            f"lw < mw < hw power holds in {fc['ordered']}/30, the chance rate (5/30).", ""]

    f6 = psd["fig6"]
    out += ["## Fig. 6: clean vs noisy PSD", "",
            "| Quantity | Paper | Ours |", "|---|---|---|",
            f"| Example pair, noisy/clean power | {paper.FIG6['ratio']} | no released pair matches ({f6['exact_matches']} of 25,440) |",
            f"| Group means, noisy (31-40) / clean (01-30) | n/a | {f6['group_ratio']:.2f} |", "",
            "- The released code's docstring example `Clean_276.EDF` is device record 276, which is `sub31_lw`, a *noisy* "
            "subject in the release, and its 2.15 Hz peak equals Fig. 6's clean peak. `Noisy_256.EDF` (record 256) is not released.", ""]

    f7 = cor["fig7"]
    out += ["## Fig. 7: channel correlation", "",
            "| Panel | Paper label | Recording | RMSE vs digitised figure | r | Runner-up RMSE |", "|---|---|---|---|---|---|"]
    for p in ["clean", "noisy"]:
        out.append(f"| {p} | {p} no-workload | {f7[p]['recording']} ({f7[p]['group']} subject) | {f7[p]['rmse']:.3f} | "
                   f"{f7[p]['r']:.3f} | {f7[p]['runner_up_rmse']:.3f} |")
    g = cor["group"]
    out += ["", f"- Group level, no-workload mean inter-channel r: clean {g['nw_clean_median']:.3f}, noisy {g['nw_noisy_median']:.3f} "
            f"(Mann-Whitney p = {g['p']:.2f}); group-mean difference spans {g['diff_min']:+.2f} to {g['diff_max']:+.2f}, "
            "against about -0.27 to +0.53 in the figure.", ""]

    out += ["## Fig. 8: BEAM maps", "",
            "Not reproducible: the maps are not output of the released `beam_topography.py`, and no recording matches them "
            "better than shuffled maps do. The paper's claims, tested per subject with the released `compute_topomap` "
            "(workload = mean of lw, mw, hw; frontal = Fp1 Fp2 F3 F4, posterior = P3 P4 O1 O2; Wilcoxon):", "",
            "| Group | Frontal theta W > NW | p | Posterior alpha NW > W | p |", "|---|---|---|---|---|"]
    for k, v in beam["claims"].items():
        out.append(f"| {k} | {v['theta_up']}/{v['n']} (median ratio {v['theta_ratio']:.2f}) | {v['theta_p']:.3f} | "
                   f"{v['alpha_down']}/{v['n']} (median ratio {v['alpha_ratio']:.2f}) | {v['alpha_p']:.3f} |")
    out.append("")

    p0 = anova.iloc[0]
    t = paper.ANOVA
    out += ["## Repeated-measures ANOVA, frontal theta, 30 clean subjects", "",
            "| | F(2, 58) | p | lw-mw | lw-hw | mw-hw | Order |", "|---|---|---|---|---|---|---|",
            f"| Paper | {t['F']} | {t['p']} | {t['posthoc'][('lw', 'mw')]} | {t['posthoc'][('lw', 'hw')]} | "
            f"{t['posthoc'][('mw', 'hw')]} | lw < mw < hw |",
            f"| Ours, BEAM theta, six frontal leads | {p0.F:.2f} | {p0.p:.2f} | {p0.p_lw_mw:.2f} | {p0.p_lw_hw:.2f} | "
            f"{p0.p_mw_hw:.2f} | {p0.order} |",
            f"| Ours, best of {len(anova)} variants | {anova.F.max():.2f} | {anova.p.min():.3f} | | | | |", "",
            f"- {(anova.p < 0.05).sum()} of {len(anova)} variants (5 channel sets x 3 power measures x linear/log) reach p < 0.05; "
            f"{(anova.order == 'lw<mw<hw').sum()} rise monotonically. See `results/anova.csv`.", ""]

    out += ["## Table 3: baseline classification", "",
            "Accuracy in %. Features are not specified in the paper; ours are 2 s windows with log band power "
            "(bandpower) or band power plus time-domain descriptors (extended). Segment = stratified 10-fold over "
            "windows; subject = leave-one-subject-out.", "",
            "| Task | Group | Model | Paper | Majority | Bandpower, segment | Bandpower, subject | Extended, segment | Extended, subject |",
            "|---|---|---|---|---|---|---|---|---|"]
    main_rows = clf[clf.group.isin(["clean", "noisy"])]
    for (task, grp, model), ref in paper.TABLE3.items():
        r = main_rows[(main_rows.task == task) & (main_rows.group == grp) & (main_rows.model == model)]
        cell = lambda f, cv: f"{r[(r.features == f) & (r.cv == cv)].accuracy.iloc[0]:.1f}"
        out.append(f"| {task} | {grp} | {model} | {ref[0]:.2f} | {r.majority.iloc[0]:.1f} | {cell('bandpower', 'segment')} | "
                   f"{cell('bandpower', 'subject')} | {cell('extended', 'segment')} | {cell('extended', 'subject')} |")
    ctrl = clf[clf.group.str.startswith("clean, 10")]
    out += ["", "Sample-size control, bandpower, segment CV, mean ± SD over 10 random 10-subject subsets of the clean group: " +
            "; ".join(f"{r.task} {r.model} {r.accuracy:.1f} ± {r.accuracy_sd:.1f}" for r in ctrl.itertuples()) + ".", ""]

    (data.RESULTS / "paper_vs_ours.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
